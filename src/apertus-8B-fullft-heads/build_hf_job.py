def log(*parts):
    print(f"[{(time.time() - START) / 60:6.1f} min]", *parts, flush=True)


def upload(folder, path_in_repo, patterns):
    if not UPLOAD_REPO:
        return
    from huggingface_hub import HfApi

    try:
        HfApi().upload_folder(repo_id=UPLOAD_REPO, folder_path=str(folder), path_in_repo=f"{PREFIX}/{path_in_repo}",
                              allow_patterns=patterns, commit_message=f"{PREFIX}: {path_in_repo}")
        log("uploaded", path_in_repo, "to the private repository")
    except Exception as error:
        log(f"upload of {path_in_repo} failed: {type(error).__name__}: {str(error)[:200]}")


def fail(message):
    upload(RUN, "logs", ["*.log"])
    raise SystemExit(message)


def run(command, log_name):
    """Runs a step from WORK, streams its output and keeps it in RUN/log_name."""
    log(">", " ".join(map(str, command)))
    with open(RUN / log_name, "a") as keep:
        process = subprocess.Popen([sys.executable, *map(str, command)], cwd=WORK, stdout=subprocess.PIPE,
                                   stderr=subprocess.STDOUT, text=True)
        for line in process.stdout:
            keep.write(line)
            print(line, end="", flush=True)
    if process.wait() != 0:
        fail(f"step failed, see {log_name}")


def run_parallel(commands, log_names, every=60):
    """Runs several steps at once; prints the last line of each log every minute."""
    processes = []
    for command, name in zip(commands, log_names):
        log(">", " ".join(map(str, command)))
        keep = open(RUN / name, "a")
        processes.append((subprocess.Popen([sys.executable, *map(str, command)], cwd=WORK, stdout=keep,
                                           stderr=subprocess.STDOUT, text=True), keep, name))
    while any(p.poll() is None for p, _, _ in processes):
        time.sleep(every)
        for _, keep, name in processes:
            keep.flush()
            lines = (RUN / name).read_text(errors="replace").strip().splitlines()
            log(name, "|", lines[-1][:200] if lines else "")
    for _, keep, _ in processes:
        keep.close()
    failed = [name for p, _, name in processes if p.returncode != 0]
    for name in failed:
        print((RUN / name).read_text(errors="replace")[-3000:], flush=True)
    if failed:
        fail(f"steps failed: {failed}")


def unpack():
    RUN.mkdir(parents=True, exist_ok=True)
    with tarfile.open(fileobj=io.BytesIO(base64.b64decode(BUNDLE)), mode="r:gz") as archive:
        archive.extractall(WORK, filter="data")
    sys.path[:0] = [str(WORK / FOLDER), str(WORK / "@@VLH@@"), str(WORK / "src")]


def download_data():
    from kaggle.api.kaggle_api_extended import KaggleApi

    api = KaggleApi()
    api.authenticate()
    api.competition_download_files("hackapertus-galaxus", path=str(DATA), quiet=True, unzip=True)
    (DATA / "final_encrypted.bin").unlink(missing_ok=True)  # the final images are never used here
    assert hashlib.sha256((DATA / "train.csv").read_bytes()).hexdigest() == TRAIN_SHA256, "train.csv changed"
    log("competition data downloaded")


def download_model():
    import ft_encode

    ft_encode.model_dir(full=True)
    log("Apertus downloaded")


def check():
    """Everything that can fail before the GPU: secrets, data access, gated model, real tokenizer and template."""
    from kaggle.api.kaggle_api_extended import KaggleApi

    import encoders
    import ft_encode
    import torch
    from transformers import AutoConfig, AutoTokenizer

    api = KaggleApi()
    api.authenticate()
    log("kaggle access ok:", len(api.competition_list_files("hackapertus-galaxus").files) > 0)
    directory = ft_encode.model_dir(full=False)
    config = AutoConfig.from_pretrained(directory)
    builder = encoders.PromptBuilder(AutoTokenizer.from_pretrained(directory), config.image_token_offset, 0)
    ids = builder.ids({"product_title": "Test"}, (2, 3), torch.arange(6, dtype=torch.int32))
    assert encoders.PREFIX_SLOT not in ids, "no soft-token slots without SigLIP"
    assert sum(config.image_token_offset <= i < config.image_token_offset + 131072 for i in ids) == 6
    log("gated model and tokenizer ok:", len(ids), "tokens for a 2x3 image,", config.text_config.num_hidden_layers,
        "layers")
    try:
        import bitsandbytes

        log("bitsandbytes", bitsandbytes.__version__, "imports")
    except Exception as error:
        log(f"bitsandbytes does not import on this machine ({type(error).__name__}: {error}); the GPU job checks it")
    if UPLOAD_REPO:
        from huggingface_hub import HfApi

        HfApi().create_repo(UPLOAD_REPO, private=True, exist_ok=True)
        assert HfApi().repo_info(UPLOAD_REPO).private, f"{UPLOAD_REPO} is not private"
    log("CHECK OK")


def main():
    unpack()
    assert os.environ.get("HF_TOKEN") and os.environ.get("KAGGLE_API_TOKEN"), "secrets HF_TOKEN and KAGGLE_API_TOKEN"
