MODE = os.environ.get("MODE", "train")
SPLIT = os.environ.get("SPLIT", "small")
UPLOAD_REPO = os.environ.get("UPLOAD_REPO", "")
# A folder per run in UPLOAD_REPO, so that a new run never overwrites the weights of an earlier one.
