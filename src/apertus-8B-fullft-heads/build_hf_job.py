"""Builds data/hf_jobs/hf_job_fullft.py, a self-contained Hugging Face Jobs script for the full finetuning.

The generated file carries the code of src/ (this folder, the data/encoder/head code of
apertus-8B-vadapter-lora-heads and src/common) and the SHA-256 of train.csv; no image ids or labels. It is written
under data/ (git-ignored) like the other jobs. The job downloads the competition data from Kaggle and Apertus from
Hugging Face onto its own disk, and uploads the checkpoint, predictions and logs to a PRIVATE repository.

  PHASE=1 (default)  VQ cache of training_rows (ENCODE_WORKERS processes) -> smoke test (3 steps) -> train 3 epochs
                     (internal validation picks the checkpoint) -> end-to-end prediction of coverage, scored with
                     metric.py -> optional dev predictions
  PHASE=2            VQ cache of all labeled images -> train EPOCHS epochs, no validation -> dev predictions

Environment of the job (-e NAME=value):
  UPLOAD_REPO      required, e.g. <user>/apertus-8b-galaxus-fullft (created private if missing)
  TRAIN_ARGS       extra arguments for ft_train.py, e.g. "--max-minutes 240"
  EPOCHS           phase 2 only: the epochs chosen in phase 1
  SIDE             VQ image side, default 256
  ENCODE_WORKERS   VQ processes sharing the GPU, default 3
  PREDICT_DEV      1 to also predict dev.csv in phase 1 (a file in the private repo; nothing is submitted)
  NO_CONTEXT_CHECK 1 to also predict coverage without product context
  CHECK_ONLY       1 to only check secrets, data and model access and the real tokenizer (a CPU is enough)

Hardware: one GPU with bf16 and >= 80 GB (about 60 GB used). Default rtx-pro-6000 (96 GB, 2.75 $/h on 27
November 2026, `hf jobs hardware`); a100-large (80 GB, 2.50 $/h) also fits. The job timeout caps the cost.

  python src/apertus-8B-fullft-heads/build_hf_job.py
  export HF_TOKEN=$(cat ~/.cache/huggingface/token) KAGGLE_API_TOKEN=$(cat ~/.kaggle/access_token)
  hf jobs uv run --flavor cpu-upgrade --timeout 20m --secrets HF_TOKEN --secrets KAGGLE_API_TOKEN \\
      -e CHECK_ONLY=1 data/hf_jobs/hf_job_fullft.py
  hf jobs uv run --flavor rtx-pro-6000 --timeout 5h --secrets HF_TOKEN --secrets KAGGLE_API_TOKEN \\
      -e UPLOAD_REPO=<user>/apertus-8b-galaxus-fullft -e TRAIN_ARGS="--max-minutes 230" \\
      data/hf_jobs/hf_job_fullft.py
"""

