"""Builds data/hf_jobs/hf_job_heads.py, a self-contained Hugging Face Jobs script for the heads experiment.

The generated file carries the code of src/ and, for the small split, the image ids of data/heads_split/. It holds
competition ids, so it is written under data/ (git-ignored); `hf jobs` copies it to a private bucket of the account.

What the job does: downloads the competition data from Kaggle (job disk only) and Apertus from Hugging Face,
extracts the features (first 16 images as a smoke test), trains the four head variants, prints the scores, and
uploads features, predictions, head weights and logs to a PRIVATE repository (UPLOAD_REPO). With CHECK_ONLY=1 it
only verifies the Kaggle and model access and runs the real processor on synthetic images (a CPU is enough).

Secrets come from the environment, never from the command line or the repository:

    python src/micro-training/apertus-8B-heads/build_hf_job.py
    export HF_TOKEN=$(cat ~/.cache/huggingface/token) KAGGLE_API_TOKEN=$(cat ~/.kaggle/access_token)
    hf jobs uv run --flavor cpu-upgrade --timeout 20m --secrets HF_TOKEN --secrets KAGGLE_API_TOKEN \\
        -e CHECK_ONLY=1 data/hf_jobs/hf_job_heads.py
    hf jobs uv run --flavor h200 --timeout 1h --secrets HF_TOKEN --secrets KAGGLE_API_TOKEN \\
        -e UPLOAD_REPO=<user>/galaxus-heads-private data/hf_jobs/hf_job_heads.py

The timeout caps the cost: the job is stopped when it expires.
"""

