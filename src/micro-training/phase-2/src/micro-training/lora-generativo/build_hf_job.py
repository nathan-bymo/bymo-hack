"""Builds hf_job.py, the self-contained Hugging Face Jobs script of the Apertus v1.5 8B LoRA (phase 1).

hf_job.py carries the code of this folder and of src/common as an embedded archive, so the job needs neither the
repository nor a code upload. Rebuild after any change, then launch (secrets come from the environment, never
from the command line or the repository):

    python src/micro-training/lora-generativo/build_hf_job.py
    HF_TOKEN=$(cat ~/.cache/huggingface/token) KAGGLE_API_TOKEN=$(cat ~/.kaggle/access_token) \\
        hf jobs uv run --flavor h200 --timeout 6h --secrets HF_TOKEN --secrets KAGGLE_API_TOKEN \\
        -e UPLOAD_REPO=<user>/apertus-8b-galaxus-lora src/micro-training/lora-generativo/hf_job.py

Prototype run (train on data/prototype_splits/train_1500.csv, score on validation_450.csv and on coverage). The
ids of the two csv files travel as the secret PROTOTYPE_IDS, never as a file or in the repository:

    PROTOTYPE_IDS=$(python src/micro-training/lora-generativo/build_hf_job.py --pack-prototype data/prototype_splits) \\
    HF_TOKEN=... KAGGLE_API_TOKEN=... hf jobs uv run --flavor h200 --timeout 3h \\
        --secrets HF_TOKEN --secrets KAGGLE_API_TOKEN --secrets PROTOTYPE_IDS \\
        -e PART=prototype_train -e SIDE=256 -e TRAIN_HOURS=2 -e UPLOAD_REPO=<user>/apertus-8b-galaxus-lora \\
        src/micro-training/lora-generativo/hf_job.py

What the job does: downloads the competition data from Kaggle (into the job's disk only, deleted with the job) and
Apertus from Hugging Face, computes the VQ codes, trains on common.splits.training_rows (or the prototype train
split), scores the final adapter on the coverage set (and on the prototype validation split), and uploads
adapters, logs and scores (never data or labels) to the private model repo.
"""

import base64
import io
import tarfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parents[1]
FILES = {
    "common/images.py": SRC / "training" / "common" / "images.py",
    "common/prompt.py": SRC / "training" / "common" / "prompt.py",
    "common/splits.py": SRC / "training" / "common" / "splits.py",
    **{name: HERE / name for name in ("apertus_lora.py", "encode.py", "train.py", "evaluate.py")},
}

TEMPLATE = '''# /// script
# requires-python = ">=3.11"
# dependencies = [
#   "torch==2.8.0",
#   "transformers[vision] @ git+https://github.com/swiss-ai/transformers.git@3797303dda74844e3d1f8977ff5518bb91f818b4",
#   "peft==0.22.0",
#   "accelerate==1.16.0",
#   "safetensors",
#   "huggingface_hub",
#   "pandas>=2.1",
#   "pillow",
#   "kaggle==2.2.5",
#   "six",
# ]
# ///
"""Hugging Face Job: QLoRA-free LoRA of Apertus v1.5 8B in bf16 on one GPU. Generated by build_hf_job.py."""

import base64
import io
import os
import subprocess
import sys
import tarfile
import threading
import time
from pathlib import Path

START = time.time()
SETTINGS = {
    "SIDE": int(os.environ.get("SIDE", 384)),
    "EPOCHS": float(os.environ.get("EPOCHS", 3)),
    "PART": os.environ.get("PART", "training"),
    "BATCH": int(os.environ.get("BATCH", 4)),
    "ACCUMULATION": int(os.environ.get("ACCUMULATION", 4)),
    "TRAIN_HOURS": float(os.environ.get("TRAIN_HOURS", 4.5)),
    "UPLOAD_REPO": os.environ.get("UPLOAD_REPO", ""),
    "PREFIX": os.environ.get("PREFIX", ""),
    "SHARDS": int(os.environ.get("SHARDS", 3)),
}
PHASES = {"training": "phase1", "all": "phase2", "prototype_train": "prototype"}
if not SETTINGS["PREFIX"]:
    SETTINGS["PREFIX"] = f"{PHASES[SETTINGS['PART']]}-{SETTINGS['SIDE']}"
WORK = Path(os.environ.get("WORK", "/tmp/work"))
CODE, DATA, MODEL, RUN = WORK / "code", WORK / "data", WORK / "model", WORK / "run"
BUNDLE = "@@BUNDLE@@"


def log(*parts):
    print(f"[{(time.time() - START) / 60:6.1f} min]", *parts, flush=True)


def run(command, log_name):
    """Runs a step, streams its output and keeps it in RUN/log_name."""
    log(">", " ".join(map(str, command)))
    with open(RUN / log_name, "a") as keep:
        process = subprocess.Popen(list(map(str, command)), cwd=CODE, stdout=subprocess.PIPE,
                                   stderr=subprocess.STDOUT, text=True)
        for line in process.stdout:
            keep.write(line)
            if "warn" not in line.lower():
                print(line, end="", flush=True)
        return process.wait()


def download_data():
    from kaggle.api.kaggle_api_extended import KaggleApi

    api = KaggleApi()
    api.authenticate()
    api.competition_download_files("hackapertus-galaxus", path=str(DATA), quiet=True, unzip=True)
    (DATA / "final_encrypted.bin").unlink(missing_ok=True)  # the final images are never used for training
    log("competition data:", sorted(p.name for p in DATA.iterdir()))


def download_model():
    from huggingface_hub import snapshot_download

    snapshot_download("swiss-ai/Apertus-v1.5-8B", local_dir=MODEL)
    log("model:", sorted(p.name for p in MODEL.iterdir()))


def encode(part, mirrors=True):
    processes = []
    for shard in range(SETTINGS["SHARDS"]):
        command = [sys.executable, "encode.py", "--model-dir", MODEL, "--data-dir", DATA, "--side", SETTINGS["SIDE"],
                   "--part", part, "--shard", shard, "--num-shards", SETTINGS["SHARDS"], "--out", RUN / "codes"]
        if not mirrors:
            command.append("--no-mirrors")
        keep = open(RUN / f"encode_{part}_{shard}.log", "w")
        processes.append(subprocess.Popen(list(map(str, command)), cwd=CODE, stdout=keep, stderr=subprocess.STDOUT))
    codes = [p.wait() for p in processes]
    for shard in range(SETTINGS["SHARDS"]):
        lines = [l for l in open(RUN / f"encode_{part}_{shard}.log") if "warn" not in l.lower()]
        print("".join(lines[-3:]), end="", flush=True)
    assert codes == [0] * SETTINGS["SHARDS"], f"encoding {part} failed: {codes}"


def upload_run():
    if not SETTINGS["UPLOAD_REPO"]:
        return
    from huggingface_hub import HfApi

    # Logs, settings and scores only: no codes, no predictions, no data.
    patterns = ["*.log", "*.json", "*.txt"]
    HfApi().upload_folder(repo_id=SETTINGS["UPLOAD_REPO"], folder_path=str(RUN), path_in_repo=SETTINGS["PREFIX"],
                          allow_patterns=patterns, commit_message=f"logs and scores of {SETTINGS['PREFIX']}")
    log("uploaded logs and scores to", SETTINGS["UPLOAD_REPO"], SETTINGS["PREFIX"])


def main():
    for folder in (CODE, DATA, MODEL, RUN):
        folder.mkdir(parents=True, exist_ok=True)
    with tarfile.open(fileobj=io.BytesIO(base64.b64decode(BUNDLE)), mode="r:gz") as archive:
        archive.extractall(CODE, filter="data")
    log("settings:", SETTINGS)
    assert os.environ.get("HF_TOKEN") and os.environ.get("KAGGLE_API_TOKEN"), "secrets HF_TOKEN and KAGGLE_API_TOKEN"
    if SETTINGS["PART"].startswith("prototype"):
        assert os.environ.get("PROTOTYPE_IDS"), "secret PROTOTYPE_IDS (build_hf_job.py --pack-prototype)"
    if SETTINGS["UPLOAD_REPO"]:
        from huggingface_hub import HfApi

        HfApi().create_repo(SETTINGS["UPLOAD_REPO"], private=True, exist_ok=True)
    import torch

    log("torch", torch.__version__, "GPU", torch.cuda.get_device_name(0) if torch.cuda.is_available() else "none")
    (RUN / "settings.json").write_text(__import__("json").dumps(SETTINGS, indent=2))
    if os.environ.get("CHECK_ONLY"):
        from kaggle.api.kaggle_api_extended import KaggleApi
        from huggingface_hub import model_info

        api = KaggleApi()
        api.authenticate()
        log("kaggle files:", [f.name for f in api.competition_list_files("hackapertus-galaxus").files][:3])
        log("apertus access:", model_info("swiss-ai/Apertus-v1.5-8B").id)
        upload_run()
        log("check ok")
        return

    threads = [threading.Thread(target=download_data), threading.Thread(target=download_model)]
    for thread in threads:
        thread.start()
    for thread in threads:
        thread.join()
    assert (DATA / "train.csv").exists() and (MODEL / "config.json").exists(), "a download failed, see above"

    encode(SETTINGS["PART"])
    log("training codes done")
    deadline = START + SETTINGS["TRAIN_HOURS"] * 3600
    train = [sys.executable, "train.py", "--precision", "bf16", "--model-dir", MODEL, "--data-dir", DATA,
             "--codes", RUN / "codes", "--out", RUN, "--part", SETTINGS["PART"], "--side", SETTINGS["SIDE"],
             "--epochs", SETTINGS["EPOCHS"], "--deadline", deadline, "--batch", SETTINGS["BATCH"],
             "--accumulation", SETTINGS["ACCUMULATION"], "--upload-repo", SETTINGS["UPLOAD_REPO"],
             "--upload-prefix", SETTINGS["PREFIX"]]
    code = run(train + ["--no-grad-ckpt"], "train.log")
    if code != 0 and "OutOfMemory" in (RUN / "train.log").read_text():
        log("out of memory without gradient checkpointing: again with it")
        code = run(train, "train.log")
    upload_run()
    assert code == 0, "training failed, see train.log"

    # Phase 2 has no valid score on train (src/training/common/splits.py). The prototype is also scored on its own validation split.
    evaluations = {"training": ["coverage"], "all": [], "prototype_train": ["prototype_validation", "coverage"]}
    failed = []
    for part in evaluations[SETTINGS["PART"]]:
        encode(part, mirrors=False)
        code = run([sys.executable, "evaluate.py", "--model-dir", MODEL, "--data-dir", DATA, "--codes", RUN / "codes",
                    "--adapter", RUN / "adapters" / "final", "--side", SETTINGS["SIDE"], "--part", part,
                    "--name", part, "--out", RUN], f"eval_{part}.log")
        for answers in RUN.glob("predictions_*.csv"):
            answers.unlink()  # model answers on train images: not uploaded
        upload_run()
        if code != 0:
            failed.append(part)
    assert not failed, f"evaluation failed on {failed}, see eval_*.log (the adapters are uploaded)"
    log("all done")


if __name__ == "__main__":
    main()
'''


def main():
    import sys

    if sys.argv[1:2] == ["--pack-prototype"]:  # prints the value of the PROTOTYPE_IDS secret
        sys.path.insert(0, str(HERE))
        import apertus_lora

        print(apertus_lora.pack_prototype_ids(sys.argv[2]))
        return
    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode="w:gz") as archive:
        for name, path in FILES.items():
            archive.add(path, arcname=name)
    bundle = base64.b64encode(buffer.getvalue()).decode()
    out = HERE / "hf_job.py"
    out.write_text(TEMPLATE.replace("@@BUNDLE@@", bundle))
    print(f"{out}: {len(FILES)} files, {len(bundle) // 1024} KB bundle")


if __name__ == "__main__":
    main()
