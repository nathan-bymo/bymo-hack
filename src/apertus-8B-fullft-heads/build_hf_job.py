def train_csv():
    for path in (ROOT / "data" / "train.csv", ROOT / "data" / "hackapertus-galaxus" / "train.csv"):
        if path.exists():
            return path
    raise SystemExit("train.csv not found under data/ or data/hackapertus-galaxus/")


def main():
    members = {name: (ROOT / name).read_bytes() for name in FILES}
    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode="w:gz") as archive:
        for name, content in members.items():
            info = tarfile.TarInfo(name)
            info.size = len(content)
            archive.addfile(info, io.BytesIO(content))
    out = ROOT / "data" / "hf_jobs" / "hf_job_fullft.py"
    out.parent.mkdir(parents=True, exist_ok=True)
    train_hash = hashlib.sha256(train_csv().read_bytes()).hexdigest()
    out.write_text(TEMPLATE.replace("@@FOLDER@@", FOLDER).replace("@@VLH@@", VLH).replace("@@TRAIN_SHA256@@", train_hash)
                   .replace("@@BUNDLE@@", base64.b64encode(buffer.getvalue()).decode()))
    print(f"{out}: {len(members)} files, {out.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
