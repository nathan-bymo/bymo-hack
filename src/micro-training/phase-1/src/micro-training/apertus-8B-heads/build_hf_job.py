def main():
    import pandas as pd

    members = {name: (ROOT / name).read_bytes() for name in FILES}
    missing = [str(path) for path in SMALL.values() if not path.exists()]
    if missing:
        raise SystemExit(f"missing split files: {missing}")
    ids = {name: list(pd.read_csv(path, dtype=str)["image_id"]) for name, path in SMALL.items()}
    members["split_ids.json"] = json.dumps(ids).encode()
    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode="w:gz") as archive:
        for name, content in members.items():
            info = tarfile.TarInfo(name)
            info.size = len(content)
            archive.addfile(info, io.BytesIO(content))
    out = ROOT / "data" / "hf_jobs" / "hf_job_heads.py"
    out.parent.mkdir(parents=True, exist_ok=True)
    train_hash = hashlib.sha256((ROOT / "data" / "train.csv").read_bytes()).hexdigest()
    out.write_text(TEMPLATE.replace("@@TRAIN_SHA256@@", train_hash)
                   .replace("@@BUNDLE@@", base64.b64encode(buffer.getvalue()).decode()))
    print(f"{out}: {len(members)} files, {out.stat().st_size // 1024} KB, "
          + ", ".join(f"{name} {len(value)} images" for name, value in ids.items()))


if __name__ == "__main__":
    main()
