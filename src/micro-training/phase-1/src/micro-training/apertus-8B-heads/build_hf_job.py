START = time.time()
WORK = Path(os.environ.get("WORK", "/tmp/work"))
DATA, RUN = WORK / "data", WORK / "data" / "run"
SPLIT = os.environ.get("SPLIT", "small")          # "small": 1500 + 450. "full": training_rows + coverage.
BATCH = os.environ.get("BATCH", "16")
UPLOAD_REPO = os.environ.get("UPLOAD_REPO", "")
TRAIN_SHA256 = "@@TRAIN_SHA256@@"
BUNDLE = "@@BUNDLE@@"


def log(*parts):
    print(f"[{(time.time() - START) / 60:6.1f} min]", *parts, flush=True)


def run(command, log_name):
    """Runs a step from WORK, streams its output and keeps it in RUN/log_name."""
    log(">", " ".join(map(str, command)))
    with open(RUN / log_name, "a") as keep:
        process = subprocess.Popen([sys.executable, *map(str, command)], cwd=WORK, stdout=subprocess.PIPE,
                                   stderr=subprocess.STDOUT, text=True)
        for line in process.stdout:
            keep.write(line)
            print(line, end="", flush=True)
    if process.wait() != 0:
        upload(RUN, "logs", ["*.log"])
        raise SystemExit(f"step failed, see {log_name}")


def upload(folder, path_in_repo, patterns):
    if not UPLOAD_REPO:
        return
    from huggingface_hub import HfApi

    HfApi().upload_folder(repo_id=UPLOAD_REPO, folder_path=str(folder), path_in_repo=f"{SPLIT}/{path_in_repo}",
                          allow_patterns=patterns, commit_message=f"{SPLIT}: {path_in_repo}")
    log("uploaded", path_in_repo, "to the private repository")


def unpack():
    RUN.mkdir(parents=True, exist_ok=True)
    with tarfile.open(fileobj=io.BytesIO(base64.b64decode(BUNDLE)), mode="r:gz") as archive:
        archive.extractall(WORK, filter="data")


def download_data():
    from kaggle.api.kaggle_api_extended import KaggleApi

    api = KaggleApi()
    api.authenticate()
    api.competition_download_files("hackapertus-galaxus", path=str(DATA), quiet=True, unzip=True)
    (DATA / "final_encrypted.bin").unlink(missing_ok=True)  # the final images are never used here
    log("competition data downloaded")


def download_model():
    from huggingface_hub import snapshot_download

    sys.path.insert(0, str(WORK / "src" / "micro-training" / "apertus-8B-heads"))
    sys.path.insert(0, str(WORK / "src" / "training"))
    from extract_features import MODEL_ID, MODEL_REVISION

    snapshot_download(MODEL_ID, revision=MODEL_REVISION)
    log("model downloaded")


def prepare_splits():
    """The csv files to extract, and the arguments that select the split in train_heads.py."""
    assert hashlib.sha256((DATA / "train.csv").read_bytes()).hexdigest() == TRAIN_SHA256, "train.csv changed"
    if SPLIT == "full":
        return [DATA / "train.csv"], [], ["--split", "coverage"]
    import pandas as pd

    rows = pd.read_csv(DATA / "train.csv", dtype=str, keep_default_na=False).set_index("image_id", drop=False)
    paths = {}
    for name, ids in json.loads((WORK / "split_ids.json").read_text()).items():
        paths[name] = DATA / f"{name}.csv"
        rows.loc[ids].to_csv(paths[name], index=False)
    train, evaluation = paths["train_1500"], paths["validation_450"]
    arguments = ["--train-csv", train, "--eval-csv", evaluation, "--val-fraction", "0.2"]
    return [train, evaluation], arguments, ["--rows", evaluation]


def check():
    """Everything that can fail before the GPU: secrets, data access, gated model, real processor."""
    from huggingface_hub import hf_hub_download
    from kaggle.api.kaggle_api_extended import KaggleApi
    from PIL import Image

    sys.path[:0] = [str(WORK / "src" / "micro-training" / "apertus-8B-heads"), str(WORK / "src" / "training")]
    import extract_features as X
    from transformers import AutoConfig, AutoProcessor

    api = KaggleApi()
    api.authenticate()
    log("kaggle access ok:", len(api.competition_list_files("hackapertus-galaxus").files) > 0)
    hf_hub_download(X.MODEL_ID, "config.json", revision=X.MODEL_REVISION)
    config = AutoConfig.from_pretrained(X.MODEL_ID, revision=X.MODEL_REVISION)
    processor = AutoProcessor.from_pretrained(X.MODEL_ID, revision=X.MODEL_REVISION)
    log("gated model access ok, layers:", config.text_config.num_hidden_layers)
    conversations = [
        [{"role": "user", "content": [{"type": "image", "image": Image.new("RGB", size, "white")},
                                      {"type": "text", "text": X.instruction({"product_title": title}, True)}]}]
        for size, title in (((512, 512), "a"), ((608, 432), "a much longer product title than the first one"))
    ]
    inputs = processor.apply_chat_template(conversations, add_generation_prompt=True, tokenize=True,
                                           return_dict=True, return_tensors="pt", processor_kwargs={"padding": True})
    counts = (inputs["input_ids"] == config.image_token_id).sum(1).tolist()
    assert counts == [32 * 32, 38 * 27], f"image tokens {counts}, expected {[32 * 32, 38 * 27]}"
    assert inputs["attention_mask"][:, -1].all() and "pixel_values" in inputs and "image_sizes" in inputs
    log("real processor ok: image tokens", counts, "| keys", sorted(inputs.keys()))
    if UPLOAD_REPO:
        from huggingface_hub import HfApi

        HfApi().create_repo(UPLOAD_REPO, private=True, exist_ok=True)
    log("CHECK OK")


def main():
    unpack()
