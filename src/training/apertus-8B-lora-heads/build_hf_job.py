def log(*parts):
    print(f"[{(time.time() - START) / 60:6.1f} min]", *parts, flush=True)


def upload(folder, path_in_repo, patterns):
    from huggingface_hub import HfApi

    HfApi().upload_folder(repo_id=UPLOAD_REPO, folder_path=str(folder), path_in_repo=f"{PREFIX}/{path_in_repo}",
                          allow_patterns=patterns, ignore_patterns=["README.md"],
                          commit_message=f"{PREFIX}: {path_in_repo}")
    log("uploaded", path_in_repo, "to the private repository")


def run(command, log_name, fatal=True):
    """Runs a step from WORK, streams its output and keeps it in RUN/log_name. Returns the exit code."""
    log(">", " ".join(map(str, command)))
    with open(RUN / log_name, "a") as keep:
        process = subprocess.Popen([sys.executable, *map(str, command)], cwd=WORK, stdout=subprocess.PIPE,
                                   stderr=subprocess.STDOUT, text=True)
        for line in process.stdout:
            keep.write(line)
            print(line, end="", flush=True)
    code = process.wait()
    if code != 0 and fatal:
        upload(RUN, "logs", ["*.log"])
        raise SystemExit(f"step failed, see {log_name}")
    return code


def unpack():
    RUN.mkdir(parents=True, exist_ok=True)
    with tarfile.open(fileobj=io.BytesIO(base64.b64decode(BUNDLE)), mode="r:gz") as archive:
        archive.extractall(WORK, filter="data")
    sys.path[:0] = [str(WORK / FOLDER), str(WORK / "src" / "training")]


def download_data():
    from kaggle.api.kaggle_api_extended import KaggleApi

    api = KaggleApi()
    api.authenticate()
    api.competition_download_files("hackapertus-galaxus", path=str(DATA), quiet=True, unzip=True)
    (DATA / "final_encrypted.bin").unlink(missing_ok=True)  # the final images are never used here
    log("competition data downloaded")


def download_model():
    import encoders

    encoders.model_dir()
    log("model downloaded")


def prepare_splits():
    """(csv of the small training split or None, csv of the small validation split or None)."""
    assert hashlib.sha256((DATA / "train.csv").read_bytes()).hexdigest() == TRAIN_SHA256, "train.csv changed"
    if SPLIT == "full":
        return None, None
    if not (WORK / "split_ids.json").is_file():
        raise RuntimeError("small split manifests were not available when this job was built; rebuild with both files")
    import pandas as pd

    rows = pd.read_csv(DATA / "train.csv", dtype=str, keep_default_na=False).set_index("image_id", drop=False)
    paths = {}
    for name, ids in json.loads((WORK / "split_ids.json").read_text()).items():
        paths[name] = DATA / f"{name}.csv"
        rows.loc[ids].to_csv(paths[name], index=False)
    return paths["train_1500"], paths["validation_450"]


def check():
    """Everything that can fail before the GPU: secrets, data access, gated model, real tokenizer and processor."""
    from huggingface_hub import HfApi
    from kaggle.api.kaggle_api_extended import KaggleApi

    import encoders
    import torch
    from PIL import Image
    from transformers import AutoConfig, AutoProcessor, AutoTokenizer

    api = KaggleApi()
    api.authenticate()
    log("kaggle access ok:", len(api.competition_list_files("hackapertus-galaxus").files) > 0)
    directory = encoders.model_dir()
    config = AutoConfig.from_pretrained(directory)
    builder = encoders.PromptBuilder(AutoTokenizer.from_pretrained(directory), config.image_token_offset)
    ids = builder.ids({"product_title": "Test"}, (2, 3), torch.arange(6, dtype=torch.int32))
    low = config.image_token_offset
    assert sum(low <= i < low + config.vision_tokenizer_config.codebook_size for i in ids) == 6
    batch = AutoProcessor.from_pretrained(directory).image_processor(images=[Image.new("RGB", (256, 256))],
                                                                    return_tensors="pt")
    assert batch["image_grids"].tolist() == [[16, 16]], batch["image_grids"]
    log("gated model, tokenizer, chat template and image processor ok:", len(ids), "tokens for a 2x3 image")
    HfApi().create_repo(UPLOAD_REPO, private=True, exist_ok=True)
    log("CHECK OK")


def train_step(train_csv, cache, out, extra, log_name):
    """train.py; once more with gradient checkpointing if the GPU runs out of memory."""
    rows = ["--train-csv", train_csv] if train_csv else ["--part", "training"]
    command = [f"{FOLDER}/train.py", "--cache", cache, *rows, "--out", out, "--upload-repo", UPLOAD_REPO,
               "--upload-prefix", f"{PREFIX}/model", *extra]
    if run(command, log_name, fatal=False) != 0:
        if "OutOfMemory" not in (RUN / log_name).read_text():
            upload(RUN, "logs", ["*.log"])
            raise SystemExit(f"training failed, see {log_name}")
        log("out of memory: again with gradient checkpointing")
        run([*command, "--grad-ckpt"], log_name)


def smoke(train_csv):
    """The whole chain on a few images: train, save, upload, download again, reload, same predictions."""
    import pandas as pd
    from huggingface_hub import snapshot_download

    few = DATA / "smoke_rows.csv"
    source = train_csv or DATA / "train_for_smoke.csv"
    if not train_csv:
        from common import splits

        splits.training_rows(pd.read_csv(DATA / "train.csv", dtype=str, keep_default_na=False)).to_csv(source, index=False)
    pd.read_csv(source, dtype=str, keep_default_na=False).head(96).to_csv(few, index=False)
    cache = DATA / "cache" / "smoke"
    run([f"{FOLDER}/encode.py", "--train-csv", few, "--out", cache, "--side", SIDE], "encode.log")
    extra = shlex.split(os.environ.get("TRAIN_ARGS", ""))
    train_step(few, cache, DATA / "smoke_model", [*extra, "--max-steps", SMOKE_STEPS], "smoke_train.log")
    local = DATA / "smoke_model" / "final"
    again = snapshot_download(UPLOAD_REPO, allow_patterns=[f"{PREFIX}/model/final/*"],
                              local_dir=DATA / "downloaded", force_download=True)
    remote = Path(again) / PREFIX / "model" / "final"
    outputs = []
    for name, checkpoint in (("local", local), ("downloaded", remote)):
        out = RUN / "smoke" / f"{name}.csv"
        run([f"{FOLDER}/predict.py", "--checkpoint", checkpoint, "--csv", few, "--images-root", DATA,
             "--limit", "16", "--out", out], f"smoke_predict_{name}.log")
        outputs.append(pd.read_csv(out, dtype=str))
    assert outputs[0].equals(outputs[1]), "the downloaded model does not predict like the local one"
    upload(RUN, "logs", ["*.log"])
    log("SMOKE OK: trained, saved, uploaded, downloaded and reloaded; same predictions")


def predict_dev():
    """The saved model, downloaded again: coverage (to compare with the predictions of the training job) and dev."""
    from huggingface_hub import snapshot_download

    model_path = os.environ.get("MODEL_PATH", "full-train/model/final")
    folder = snapshot_download(UPLOAD_REPO, allow_patterns=[f"{model_path}/*"], local_dir=DATA / "model_download")
    checkpoint = Path(folder) / model_path
    assert (checkpoint / "heads.pt").exists() and (checkpoint / "settings.json").exists(), f"no model in {model_path}"
    log("model downloaded from the private repository:", model_path)
    outputs = RUN / "predictions"
    run([f"{FOLDER}/predict.py", "--checkpoint", checkpoint, "--part", "coverage", "--out", outputs / "coverage.csv"],
        "predict_coverage.log")
    upload(outputs, "predictions", ["*.csv", "*.json", "*.pt"])
    run(["src/scripts/eval_prompt.py", outputs / "coverage.csv", "--split", "coverage", "--bootstrap", "0"],
        "scores_coverage.log")
    run([f"{FOLDER}/predict.py", "--checkpoint", checkpoint, "--csv", DATA / "dev.csv", "--out", outputs / "dev.csv"],
        "predict_dev.log")
    upload(outputs, "predictions", ["*.csv", "*.json", "*.pt"])
    upload(RUN, "logs", ["*.log"])
    log("ALL DONE")


